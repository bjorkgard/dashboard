"""Owned stdio app-server; only initialization and account/rateLimits/read.

Protocol validated against the public schema generated by Codex 0.167.2 in an
empty temporary CODEX_HOME. Authentication remains CLI-owned; no token reads.
"""

import asyncio
import json
import os
import signal
import tempfile
from contextlib import suppress
from importlib.metadata import version
from pathlib import Path
from typing import Any

from dayboard.core.models import ErrorCode
from dayboard.core.providers import ProviderUnavailable

_LINE = 256 * 1024
_TOTAL = 512 * 1024
_STDERR = 32 * 1024


class CodexAppServer:
    def __init__(self, source_root: str, *, timeout: float = 8) -> None:
        path = Path(source_root)
        if not path.is_absolute() or ".." in path.parts or not 0 < timeout <= 8:
            raise ValueError("Invalid Codex transport scope or budget.")
        self.source_root, self.timeout = source_root, timeout

    async def _cleanup(self, process: asyncio.subprocess.Process) -> None:
        if process.stdin is not None:
            with suppress(OSError):
                process.stdin.close()
        # Signal only the group created by start_new_session. KILL also reaps descendants
        # when the group leader has already exited; never use an inherited process group.
        with suppress(ProcessLookupError, PermissionError):
            os.killpg(process.pid, signal.SIGTERM)
        with suppress(TimeoutError, ProcessLookupError):
            await asyncio.wait_for(process.wait(), 0.3)
        with suppress(ProcessLookupError, PermissionError):
            os.killpg(process.pid, signal.SIGKILL)
        with suppress(TimeoutError, ProcessLookupError):
            await asyncio.wait_for(process.wait(), 0.3)

    async def _exchange(self, process: asyncio.subprocess.Process) -> dict[str, Any]:
        if process.stdin is None or process.stdout is None or process.stderr is None:
            raise ProviderUnavailable(ErrorCode.CODEX_SETUP_REQUIRED)
        writer, stdout, stderr = process.stdin, process.stdout, process.stderr
        total = 0

        async def send(method: str, params: dict[str, Any], identifier: int | None) -> None:
            if method not in {"initialize", "initialized", "account/rateLimits/read"}:
                raise ProviderUnavailable(ErrorCode.CODEX_SETUP_REQUIRED)
            message: dict[str, Any] = {"method": method, "params": params}
            if identifier is not None:
                message["id"] = identifier
            writer.write(json.dumps(message).encode() + b"\n")
            await writer.drain()

        async def receive(identifier: int) -> dict[str, Any]:
            nonlocal total
            for _ in range(128):
                raw = await stdout.readline()
                total += len(raw)
                if not raw or len(raw) > _LINE or total > _TOTAL:
                    raise ProviderUnavailable(ErrorCode.CODEX_SETUP_REQUIRED)
                item = json.loads(raw)
                if not isinstance(item, dict):
                    raise ProviderUnavailable(ErrorCode.CODEX_SETUP_REQUIRED)
                if "method" in item:
                    # Ignore bounded notifications; never answer server-initiated requests.
                    if "id" in item:
                        raise ProviderUnavailable(ErrorCode.CODEX_SETUP_REQUIRED)
                    continue
                if type(item.get("id")) is not int or item["id"] != identifier:
                    raise ProviderUnavailable(ErrorCode.CODEX_SETUP_REQUIRED)
                result = item.get("result")
                if "error" in item or not isinstance(result, dict):
                    raise ProviderUnavailable(ErrorCode.CODEX_SETUP_REQUIRED)
                return result
            raise ProviderUnavailable(ErrorCode.CODEX_SETUP_REQUIRED)

        async def drain_stderr() -> None:
            consumed = 0
            while raw := await stderr.read(4096):
                consumed += len(raw)
                if consumed > _STDERR:
                    raise ProviderUnavailable(ErrorCode.CODEX_SETUP_REQUIRED)

        async def dialogue() -> dict[str, Any]:
            await send(
                "initialize",
                {
                    "clientInfo": {"name": "dayboard", "version": version("dayboard")},
                    "capabilities": {
                        "experimentalApi": False,
                        "explicitGatewayOauth": True,
                    },
                },
                0,
            )
            await receive(0)
            await send("initialized", {}, None)
            await send(
                "account/rateLimits/read",
                {"excludeResetCreditDetails": True, "supportsLunaReserve": False},
                1,
            )
            return await receive(1)

        exchange = asyncio.create_task(dialogue())
        errors = asyncio.create_task(drain_stderr())
        try:
            done, _ = await asyncio.wait((exchange, errors), return_when=asyncio.FIRST_COMPLETED)
            if errors in done:
                errors.result()
            result = await exchange
            if errors.done():
                errors.result()
            return result
        finally:
            for task in (exchange, errors):
                task.cancel()
            await asyncio.gather(exchange, errors, return_exceptions=True)

    async def read_limits(self) -> dict[str, Any]:
        process: asyncio.subprocess.Process | None = None
        spawn: asyncio.Task[asyncio.subprocess.Process] | None = None
        try:
            # Avoid loading project configuration from the dashboard or selected source.
            with tempfile.TemporaryDirectory(prefix="dayboard-codex-") as cwd:
                try:
                    async with asyncio.timeout(self.timeout):
                        env = os.environ.copy()
                        env["CODEX_HOME"] = self.source_root
                        spawn = asyncio.create_task(
                            asyncio.create_subprocess_exec(
                                "codex",
                                "app-server",
                                "--listen",
                                "stdio://",
                                stdin=asyncio.subprocess.PIPE,
                                stdout=asyncio.subprocess.PIPE,
                                stderr=asyncio.subprocess.PIPE,
                                start_new_session=True,
                                cwd=cwd,
                                env=env,
                                limit=_LINE,
                            )
                        )
                        process = await asyncio.shield(spawn)
                        return await self._exchange(process)
                finally:
                    if process is None and spawn is not None:
                        with suppress(Exception):
                            process = await asyncio.shield(spawn)
                    if process is not None:
                        cleanup = asyncio.create_task(self._cleanup(process))
                        await asyncio.shield(cleanup)
        except TimeoutError:
            raise ProviderUnavailable(ErrorCode.TIMEOUT) from None
        except (OSError, ValueError, RecursionError):
            raise ProviderUnavailable(ErrorCode.CODEX_SETUP_REQUIRED) from None
